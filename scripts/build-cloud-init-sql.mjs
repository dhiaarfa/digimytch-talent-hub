#!/usr/bin/env node
/**
 * Builds supabase/cloud-init-all.sql — one file for Supabase.com SQL Editor.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migDir = join(root, "supabase/migrations");

const files = [
  "schema.sql",
  ...readdirSync(migDir)
    .filter((f) => f.endsWith(".sql"))
    .sort(),
];

let out = `-- Digimytch Talent Hub — ONE-SHOT init for Supabase.com
-- Paste this ENTIRE file in SQL Editor → Run once
-- Generated by: node scripts/build-cloud-init-sql.mjs

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS vector;

`;

for (const f of files) {
  const p = f === "schema.sql" ? join(root, f) : join(migDir, f);
  let sql = readFileSync(p, "utf8");
  if (f === "schema.sql") {
    sql = sql.replace(/CREATE EXTENSION IF NOT EXISTS "uuid-ossp";\s*/i, "");
  }
  if (f === "20260605120000_pgvector_semantic_matching.sql") {
    sql = sql.replace(/CREATE EXTENSION IF NOT EXISTS vector;\s*/i, "");
  }
  out += `\n-- ===== ${f} =====\n${sql}\n`;
}

out = out
  .replace(/storage\.vector_cosine_ops/g, "vector_cosine_ops")
  .replace(/storage\.vector/g, "vector")
  .replace(/SET search_path = public, storage/g, "SET search_path = public, extensions");

const dest = join(root, "supabase/cloud-init-all.sql");
writeFileSync(dest, out);
console.log(`✅ ${dest} (${out.length} bytes)`);
